// workmanager_android 0.9.3 assumes AGP 9 built-in Kotlin. This Flutter app
// still uses the explicit Kotlin plugin, so compile the worker with that same
// plugin when built-in Kotlin is disabled. Keep the workaround module-scoped.
subprojects {
    if (name == "workmanager_android" && providers.gradleProperty("android.builtInKotlin").orNull == "false") {
        plugins.withId("com.android.library") {
            pluginManager.apply("org.jetbrains.kotlin.android")
            tasks.withType<org.jetbrains.kotlin.gradle.tasks.KotlinCompile>().configureEach {
                compilerOptions.jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_1_8)
            }
        }
    }
}

tasks.register<Delete>("clean") {
    delete(rootProject.layout.buildDirectory)
}
